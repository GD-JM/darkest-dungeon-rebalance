"""Apply heroes/<id>/<id>.effects_edit.txt to the game data (idempotent).

For each hero:
  - effect lines that differ from vanilla -> written as "RB <ABBR> <name>" to effects/rebalance_<id>.effects.darkest
  - this hero's .info.darkest references to those effects -> renamed to the RB name
  - effects edited back to vanilla -> RB copy removed, references restored to the vanilla name
Only the hero's own files are touched. Vanilla effect files are never overridden.
Usage: python tools/apply_effect_edits.py [--mod PATH] [--game PATH] [--dry-run] [hero ...]
"""
import os, re, sys, subprocess
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from effect_common import ABBR, P, paths, load_vanilla_effects, norm_ws, EFFECT_LIST

args = sys.argv[1:]
opt = lambda k: args[args.index(k) + 1] if k in args else None
M, G = paths(opt('--mod'), opt('--game'))
dry = '--dry-run' in args
skip_vals = {opt('--mod'), opt('--game')}
only = [a for a in args if not a.startswith('--') and a not in skip_vals]
EFF = load_vanilla_effects(G)

report = []
for hero in sorted(d for d in os.listdir(os.path.join(M, 'heroes')) if os.path.isdir(os.path.join(M, 'heroes', d))):
    if only and hero not in only:
        continue
    edit = os.path.join(M, 'heroes', hero, hero + '.effects_edit.txt')
    info = os.path.join(M, 'heroes', hero, hero + '.info.darkest')
    if not os.path.exists(edit) or not os.path.exists(info):
        continue
    prefix = 'RB %s ' % ABBR[hero]
    changed, errors = {}, []
    for raw in open(edit, encoding='utf-8', errors='replace'):
        line = raw.rstrip('\r\n')
        if not line.startswith('effect:'):
            continue
        m = re.search(r'\.name\s+"([^"]+)"', line)
        if not m:
            errors.append('이름 없는 효과 줄: %s' % line[:80])
            continue
        name = m.group(1)
        if name not in EFF:
            errors.append('원본에 없는 효과 이름(이름을 바꾸지 마세요): %s' % name)
            continue
        if norm_ws(line) != norm_ws(EFF[name][0]):
            changed[name] = line

    # 1) rebalance effects file
    reb = os.path.join(M, 'effects', 'rebalance_%s.effects.darkest' % hero)
    if changed:
        body = ['// Rebalance mod - %s effects edited in heroes/%s/%s.effects_edit.txt' % (hero, hero, hero),
                '// Generated by tools/apply_effect_edits.py. Do not edit here; edit the effects_edit.txt and re-apply.', '']
        for name, line in changed.items():
            body.append('// from %s' % EFF[name][1])
            body.append(line.replace('"%s"' % name, '"%s%s"' % (prefix, name), 1))
        new_text = '\r\n'.join(body) + '\r\n'
        old_text = open(reb, encoding='utf-8').read() if os.path.exists(reb) else None
        if old_text != new_text.replace('\r\n', '\n') and not dry:
            os.makedirs(os.path.dirname(reb), exist_ok=True)
            with open(reb, 'wb') as fh:
                fh.write(new_text.encode('utf-8'))
    elif os.path.exists(reb) and not dry:
        os.remove(reb)

    # 2) hero info references
    data = open(info, 'rb').read().decode('utf-8')
    nl = '\r\n' if '\r\n' in data else '\n'
    renamed = []

    def fix_list(m):
        def fix_name(nm):
            base = nm[len(prefix):] if nm.startswith(prefix) else nm
            if base not in EFF:
                return nm
            target = prefix + base if base in changed else base
            if target != nm:
                renamed.append('%s -> %s' % (nm, target))
            return target
        names = re.sub(r'"([^"]*)"', lambda q: '"%s"' % fix_name(q.group(1)), m.group(2))
        return m.group(1) + names

    new_lines = []
    for l in data.split(nl):
        if l.startswith('//'):
            new_lines.append(l)
            continue
        fixed = EFFECT_LIST.sub(fix_list, re.sub(r'"\.(?=[A-Za-z_])', '" .', l)) if EFFECT_LIST.search(re.sub(r'"\.(?=[A-Za-z_])', '" .', l)) else l
        new_lines.append(fixed if fixed != re.sub(r'"\.(?=[A-Za-z_])', '" .', l) else l)
    new_data = nl.join(new_lines)
    if new_data != data and not dry:
        with open(info, 'wb') as fh:
            fh.write(new_data.encode('utf-8'))
    if changed or renamed or errors:
        report.append((hero, sorted(changed), renamed, errors))

if not report:
    print('변경된 효과 없음 (게임 데이터 수정 없음)')
for hero, ch, rn, er in report:
    print('[%s] 변경된 효과 %d개: %s' % (hero, len(ch), ', '.join(ch) or '-'))
    print('   참조 변경 %d곳%s' % (len(rn), (': ' + '; '.join(sorted(set(rn)))[:400]) if rn else ''))
    for e in er:
        print('   오류:', e)
if report and not dry:
    mk = os.path.join(M, 'tools', 'make_modfiles.py')
    if os.path.exists(mk):
        print(subprocess.run([sys.executable, mk], capture_output=True, text=True).stdout.strip())
